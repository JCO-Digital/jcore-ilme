<?php
/**
 * Login screen (wp-login.php) in each site's look.
 *
 * Ydin loads dist/css/wplogin.css (src/scss/partials/_login.scss) and shows
 * the custom logo; includes/sites.php gives the login page the site's light
 * logo. The login page doesn't print theme.json's custom properties or font
 * faces, so they are printed here: the stylesheet can then use the presets
 * (`var(--wp--preset--color--dark)`), which follow each site's colours and
 * heading font (sites/<key>.json).
 *
 * @package Jcore\Ilme
 */

namespace Jcore\Ilme;

defined( 'ABSPATH' ) || exit;

/**
 * Print the current site's preset custom properties and font faces.
 *
 * @return void
 */
function login_presets(): void {
	printf(
		"<style id=\"jcore-login-presets\">\n%s\n</style>\n",
		wp_get_global_stylesheet( array( 'variables' ) ) // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- CSS generated by core from theme.json.
	);
	wp_print_font_faces();
}
add_action( 'login_head', __NAMESPACE__ . '\\login_presets' );
